// B3-AC1
func TestClassify(t *testing.T) {
	if len(classifyCases) < 200 {
		t.Fatalf("classifier table has %d rows, want ≥ 200", len(classifyCases))
	}
	for _, tt := range classifyCases {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.want, diet.Classify(tt.name))
		})
	}
}
